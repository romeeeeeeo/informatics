#!/bin/bash


echo "========================================="
echo "   ЗАДАНИЕ 1: БАЗОВЫЙ ВЫВОД КОЛОНОК"
echo "========================================="
echo

if [ ! -f "students.txt" ]; then
    echo "❌ Ошибка: файл students.txt не найден!"
    exit 1
fi

echo "📄 Содержимое файла students.txt:"
echo "----------------------------------------"
cat students.txt
echo

echo "📋 1. Только имена студентов (первая колонка):"
echo "----------------------------------------"
awk '{print $1}' students.txt
echo

echo "📊 2. Только оценки (вторая колонка):"
echo "----------------------------------------"
awk '{print $2}' students.txt
echo

echo "🔢 3. Номер строки и имя студента:"
echo "----------------------------------------"
awk '{print "Строка " NR ": " $1}' students.txt
echo

echo "📌 Дополнительная информация:"
echo "----------------------------------------"
echo "Всего строк в файле: $(wc -l < students.txt)"
echo "Первая строка: $(head -1 students.txt)"
echo "Последняя строка: $(tail -1 students.txt)"

echo
echo "========================================="
echo "        ЗАДАНИЕ 1 ВЫПОЛНЕНО"
echo "========================================="
