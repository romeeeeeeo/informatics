#!/bin/bash


echo "========================================="
echo "   ЗАДАНИЕ 4: ОБРАБОТКА CSV-ФАЙЛА"
echo "========================================="
echo

if [ ! -f "data.csv" ]; then
    echo "❌ Ошибка: файл data.csv не найден!"
    exit 1
fi


echo "📄 Содержимое файла data.csv:"
echo "----------------------------------------"
cat data.csv
echo

echo "🔹 1. Вывод всех полей (разделитель - запятая):"
echo "----------------------------------------"
awk -F "," '{print "ID: " $1 ", Товар: " $2 ", Цена: " $3}' data.csv
echo

echo "🔹 2. Только названия товаров:"
echo "----------------------------------------"
awk -F "," 'NR > 1 {print "   " $2}' data.csv
echo

echo "🔹 3. Товары дороже 5000 рублей:"
echo "----------------------------------------"
awk -F "," 'NR > 1 && $3 > 5000 {print "   " $2 " - " $3 " руб."}' data.csv
echo

echo "🔹 4. Альтернативный способ (BEGIN {FS=\",\"}):"
echo "----------------------------------------"
awk 'BEGIN {FS=","} {print $1 "\t" $2 "\t" $3}' data.csv
echo

echo "🔹 5. Сумма всех товаров (без заголовка):"
echo "----------------------------------------"
total=$(awk -F "," 'NR > 1 {sum += $3} END {print sum}' data.csv)
echo "   Общая сумма: $total руб."

average=$(awk -F "," 'NR > 1 {sum += $3; count++} END {print sum/count}' data.csv)
echo "   Средняя цена: $average руб."
echo

echo "🔹 6. Форматированный вывод (таблица):"
echo "----------------------------------------"
awk -F "," '
BEGIN {
    printf "%-5s %-25s %10s\n", "ID", "Товар", "Цена"
    printf "%-5s %-25s %10s\n", "----", "-------------------------", "----------"
}
NR > 1 {
    printf "%-5s %-25s %10s\n", $1, $2, $3
}' data.csv

echo
echo "========================================="
echo "        ЗАДАНИЕ 4 ВЫПОЛНЕНО"
echo "========================================="
