#!/bin/bash

# Скрипт для создания и удаления файлов в прямом и обратном порядке
# Демонстрирует работу циклов for и while

echo "========================================="
echo "     ПУТЕШЕСТВИЕ ФАЙЛОВ (ROUNDTRIP)"
echo "========================================="
echo

# --- Часть 1: Создание файлов с помощью цикла for ---
echo "🔨 ШАГ 1: СОЗДАНИЕ ФАЙЛОВ (ЦИКЛ FOR)"
echo "-----------------------------------------"

# Создаём 10 файлов от test1.txt до test10.txt
for i in {1..10}; do
    filename="test${i}.txt"
    # Создаём файл и записываем в него дату создания и номер
    echo "Файл test${i}.txt создан $(date)" > "$filename"
    echo "   ✅ Создан: $filename"
    
    # Небольшая пауза для наглядности (0.1 секунды)
    sleep 0.1
done

echo
echo "📋 Список созданных файлов:"
ls -la test*.txt 2>/dev/null || echo "Файлы не найдены"

echo
echo "-----------------------------------------"
echo "🔨 Всего создано файлов: $(ls -1 test*.txt 2>/dev/null | wc -l)"
echo

# --- Часть 2: Удаление файлов в обратном порядке с помощью цикла while ---
echo "🗑️  ШАГ 2: УДАЛЕНИЕ ФАЙЛОВ В ОБРАТНОМ ПОРЯДКЕ (ЦИКЛ WHILE)"
echo "-----------------------------------------"

# Задаём начальный счётчик
counter=10

# Цикл while выполняется, пока счётчик больше или равен 1
while [ $counter -ge 1 ]; do
    filename="test${counter}.txt"
    
    # Проверяем, существует ли файл
    if [ -f "$filename" ]; then
        echo "   🗑️  Удаляется: $filename"
        rm "$filename"
        
        # Проверяем, успешно ли удалился файл
        if [ ! -f "$filename" ]; then
            echo "      ✅ Удалён"
        else
            echo "      ❌ Ошибка удаления"
        fi
    else
        echo "   ⚠️  Файл $filename не найден"
    fi
    
    # Уменьшаем счётчик на 1
    counter=$((counter - 1))
    
    # Небольшая пауза для наглядности
    sleep 0.2
done

echo
echo "-----------------------------------------"
echo "📋 Проверка: остались ли файлы?"
ls -la test*.txt 2>/dev/null || echo "✅ Все файлы успешно удалены!"

echo
echo "========================================="
echo "        ОПЕРАЦИЯ ЗАВЕРШЕНА"
echo "========================================="
