#!/bin/bash



check_root() {
       local user_id=$EUID
    local script_name=$(basename "$0")
    
    echo "🔍 Проверка прав доступа..."
    echo "   Текущий UID: $user_id"
    
        if [ "$user_id" -ne 0 ]; then
        echo
        echo "╔════════════════════════════════════════════════╗"
        echo "║     ❌ ОШИБКА: ТРЕБУЮТСЯ ПРАВА ROOT!        ║"
        echo "╠════════════════════════════════════════════════╣"
        echo "║ Данный скрипт должен запускаться от имени    ║"
        echo "║ суперпользователя (root).                     ║"
        echo "║                                                ║"
        echo "║ Попробуйте: sudo ./$script_name               ║"
        echo "╚════════════════════════════════════════════════╝"
        echo
        
               exit 1
    else
        echo "   ✅ Права root подтверждены!"
        echo
    fi
}


echo "========================================="
echo "     СКРИПТ С ПРОВЕРКОЙ ПРАВ ROOT"
echo "========================================="
echo

check_root

echo "========================================="
echo "✅ ДОСТУП РАЗРЕШЁН: СКРИПТ ВЫПОЛНЯЕТСЯ"
echo "========================================="
echo

echo "📁 Информация о системе (требует прав root):"
echo "-----------------------------------------"

if [ -f "/etc/shadow" ]; then
    echo "   - Файл /etc/shadow доступен для чтения"
    echo "   - Первые 3 строки:"
    echo "     --------------------"
    head -n 3 /etc/shadow | sed 's/^/     /'
else
    echo "   - Файл /etc/shadow не найден"
fi

echo
echo "📊 Информация о пользователях:"
echo "-----------------------------------------"
echo "   - Текущий пользователь: $(whoami)"
echo "   - UID: $EUID"
echo "   - Домашняя директория: $HOME"

echo
echo "========================================="
echo "        СКРИПТ УСПЕШНО ЗАВЕРШЁН"
echo "========================================="
