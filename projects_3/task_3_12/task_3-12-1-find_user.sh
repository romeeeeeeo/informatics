#!/bin/bash


echo "========================================="
echo "   ПОИСК ПОЛЬЗОВАТЕЛЯ В /ETC/PASSWD"
echo "========================================="
echo

echo "🔍 Ищем пользователя: $CURRENT_USER"
echo

echo "📋 Результат поиска:"
echo "----------------------------------------"
grep -n --color "^$CURRENT_USER" /etc/passwd

if [ $? -eq 0 ]; then
    echo
    echo "✅ Пользователь $CURRENT_USER найден в системе!"
else
    echo
    echo "❌ Пользователь $CURRENT_USER не найден в системе"
    echo "   (возможно, вы используете нелокальную аутентификацию)"
fi

echo
echo "========================================="
